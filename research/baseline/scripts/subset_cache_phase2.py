"""
Build Phase II-only sentence2embedding.pkl for the MSI handoff (8 GB RAM).

- Keys: every sentence produced by upstream parsing (HINT/protocol_encode.split_protocol,
  inclusion=result[0] and exclusion=result[1] if len==2 — exactly what protocol2feature looks up)
  over data/phase_II_{train,valid,test}.csv.
- Values: the exact torch tensors from the regenerated full cache — copied by reference,
  no recompute, no dtype/precision change.
- Missing-sentence behavior preserved: subset contains only keys present in the full cache;
  any sentence absent falls through protocol2feature's `if sentence in sentence_2_vec` check
  to zero vectors, identically to the full cache (count of such sentences recorded).
- Deterministic key ordering (sorted) for stable pickle bytes.
Writes: /content/hint_evidence/phase2_subset_cache/{phase2_sentence2embedding.pkl, provenance.json}
"""
import os, sys, pickle, json, hashlib, csv, time
import torch

REPO = "/content/clinical-trial-outcome-prediction"
os.chdir(REPO); sys.path.insert(0, ".")
OUT = "/content/hint_evidence/phase2_subset_cache"
os.makedirs(OUT, exist_ok=True)

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 22), b""): h.update(chunk)
    return h.hexdigest()

from HINT.protocol_encode import split_protocol, protocol2feature

t0 = time.time()
sentences = set()
per_split = {}
for split in ["train", "valid", "test"]:
    rows = list(csv.reader(open(f"data/phase_II_{split}.csv", newline="")))[1:]
    sset = set()
    for r in rows:
        res = split_protocol(r[9])
        sset.update(res[0])
        if len(res) == 2: sset.update(res[1])
    per_split[split] = {"rows": len(rows), "unique_sentences": len(sset)}
    sentences |= sset
print(f"phase II unique sentences (upstream parsing): {len(sentences)}")

full = pickle.load(open("data/sentence2embedding.pkl", "rb"))
print(f"full cache entries: {len(full)}")
missing = sorted(s for s in sentences if s not in full)

sub = {s: full[s] for s in sorted(sentences) if s in full}
with open(f"{OUT}/phase2_sentence2embedding.pkl", "wb") as f:
    pickle.dump(sub, f)

# sanity: identical features via upstream protocol2feature on sample trials (full vs subset)
import random; random.seed(0)
sample_rows = []
for split in ["train", "valid", "test"]:
    rs = list(csv.reader(open(f"data/phase_II_{split}.csv", newline="")))[1:]
    sample_rows += random.sample(rs, 3)
checks = []
for r in sample_rows:
    inc_f, exc_f = protocol2feature(r[9], full)
    inc_s, exc_s = protocol2feature(r[9], sub)
    checks.append(bool(torch.equal(inc_f, inc_s) and torch.equal(exc_f, exc_s)))
assert all(checks), "feature mismatch between full and subset cache!"

prov = {
    "created": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
    "purpose": "Phase II-only eligibility sentence embedding cache for MSI (8GB RAM) handoff",
    "full_cache": {
        "path": "/content/clinical-trial-outcome-prediction/data/sentence2embedding.pkl",
        "entries": len(full),
        "sha256": sha256("data/sentence2embedding.pkl"),
        "size_bytes": os.path.getsize("data/sentence2embedding.pkl"),
        "provenance": ("regenerated by us: keys = HINT/protocol_encode.collect_cleaned_sentence_set() "
                       "over data/raw_data.csv (513,863 sentences); model dmis-lab/biobert-base-cased-v1.1 "
                       "(= biobert_v1.1_pubmed of biobert-embedding 0.1.2); semantics = final encoder layer, "
                       "mean over all tokens incl [CLS]/[SEP], token_type_ids=1, fp32, eval mode, no grad; "
                       "numerical equivalence vs pytorch-pretrained-bert 0.6.2 verified max|d|<2e-6"),
        "upstream_stub_sha256": "8ec16a78d9c9d3646c559df239aea3f15333605ddc702eeacebf6dd3ebeff684",
    },
    "subset_procedure": ("for each row of data/phase_II_{train,valid,test}.csv: split_protocol(criteria); "
                         "collect result[0] and (if len==2) result[1] sentences — exactly the lookups "
                         "protocol2feature performs; values copied by reference from full cache (unchanged "
                         "tensors); keys sorted for deterministic pickle bytes"),
    "entries": len(sub),
    "phase2_sentences_missing_from_full_cache": len(missing),
    "per_split": per_split,
    "size_bytes": os.path.getsize(f"{OUT}/phase2_sentence2embedding.pkl"),
    "sha256": sha256(f"{OUT}/phase2_sentence2embedding.pkl"),
    "missing_sentence_behavior": ("identical to full cache: absent sentences -> protocol2feature zero vector "
                                  f"via its `if sentence in sentence_2_vec` guard; missing count = {len(missing)}"),
    "feature_equality_check": {"n_trials": len(checks), "all_equal": all(checks)},
    "usage": "place as data/sentence2embedding.pkl in the repo root on the target machine",
    "elapsed_s": round(time.time() - t0, 1),
}
json.dump(prov, open(f"{OUT}/provenance.json", "w"), indent=2)
print(json.dumps(prov, indent=2))
