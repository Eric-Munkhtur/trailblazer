"""
Experiment: 'authors' checkpoint evaluated by us' (Phase II).

Loads upstream save_model/phase_II.ckpt (full pickled HINTModel, torch.load weights_only=False
- required on torch>=2.6), evaluates valid+test with:
  - independent evaluator (continuous ROC-AUC/AP, F1@0.5, confusion; eval mode, no grad, sigmoid once)
  - upstream evaluator replication (binarized 'PR-AUC')
Runs on CPU exactly as upstream did. Compares our test predictions with authors' shipped
predictions (results/phase_II_test.csv) for provenance verification.
Writes: /content/hint_evidence/authors_checkpoint_eval/{metrics.json, preds_valid.csv, preds_test.csv}
"""
import os, sys, json, time, csv, hashlib
import numpy as np
import torch

REPO = "/content/clinical-trial-outcome-prediction"
os.chdir(REPO); sys.path.insert(0, ".")
OUT = "/content/hint_evidence/authors_checkpoint_eval"
os.makedirs(OUT, exist_ok=True)
RUN_ID = "ckpt_authors_phaseII"

t_start = time.time()
from HINT.dataloader import csv_three_feature_2_dataloader  # loads real sentence2embedding.pkl at import
from sklearn.metrics import (roc_auc_score, average_precision_score, f1_score,
                             precision_score, recall_score, accuracy_score, confusion_matrix)

device = torch.device("cpu")  # upstream eval device (learn_phaseII.py hardcodes cpu)
valid_loader = csv_three_feature_2_dataloader("data/phase_II_valid.csv", shuffle=False, batch_size=32)
test_loader = csv_three_feature_2_dataloader("data/phase_II_test.csv", shuffle=False, batch_size=32)

model = torch.load("save_model/phase_II.ckpt", weights_only=False, map_location="cpu")
model.eval()

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""): h.update(chunk)
    return h.hexdigest()

@torch.no_grad()
def predict(model, loader):
    nctids, labels, probs = [], [], []
    for nctid_lst, label_vec, smiles_lst2, icdcode_lst3, criteria_lst in loader:
        out = model.forward(smiles_lst2, icdcode_lst3, criteria_lst).view(-1)  # logits
        probs.extend(torch.sigmoid(out).cpu().tolist())  # sigmoid exactly once
        labels.extend(label_vec.tolist())
        nctids.extend(nctid_lst)
    return nctids, labels, probs

def independent_eval(p, y, threshold=0.5):
    p = np.array(p); y = np.array(y)
    pred = (p >= threshold).astype(int)
    return {
        "roc_auc": float(roc_auc_score(y, p)),
        "average_precision_continuous": float(average_precision_score(y, p)),
        "f1@0.5": float(f1_score(y, pred)),
        "precision@0.5": float(precision_score(y, pred)),
        "recall@0.5": float(recall_score(y, pred)),
        "accuracy@0.5": float(accuracy_score(y, pred)),
        "confusion_matrix@0.5 (tn,fp / fn,tp)": confusion_matrix(y, pred).tolist(),
        "n": int(len(y)), "n_pos": int(y.sum()),
    }

def upstream_eval(p, y, threshold=0.5):
    pred = [0 if x < threshold else 1 for x in p]
    return {
        "roc_auc_continuous": float(roc_auc_score(y, p)),
        "prauc_binarized_UPSTREAM": float(average_precision_score(y, pred)),
        "f1@0.5": float(f1_score(y, pred)),
    }

def save_preds(path, nctids, labels, probs, run_id):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["nctid","label","probability","predicted_class@0.5","run_id"])
        for n, l, p in zip(nctids, labels, probs):
            w.writerow([n, int(l), float(p), int(p >= 0.5), run_id])

results = {"run_id": RUN_ID,
    "experiment": "authors' checkpoint evaluated by us (Phase II)",
    "checkpoint": {"path": "save_model/phase_II.ckpt",
                   "sha256": sha256("save_model/phase_II.ckpt"),
                   "provenance": "futianfan/clinical-trial-outcome-prediction @ 8dc0497 (save_model/phase_II.ckpt, 13.8MB, full pickled HINTModel)"},
    "embedding_cache": {"pkl_sha256": sha256("data/sentence2embedding.pkl"),
                        "provenance": "regenerated by us: dmis-lab/biobert-base-cased-v1.1, final-layer mean incl [CLS]/[SEP] (see embedding_meta.json)"},
    "upstream_commit": os.popen("git rev-parse HEAD").read().strip(),
    "device": "cpu (upstream default)", "model_mode": "eval(), torch.no_grad(), sigmoid applied once to logits",
}

for name, loader in [("valid", valid_loader), ("test", test_loader)]:
    t0 = time.time()
    nctids, labels, probs = predict(model, loader)
    results[name] = {
        "independent": independent_eval(probs, labels),
        "upstream_replication": upstream_eval(probs, labels),
        "eval_seconds": round(time.time() - t0, 1),
    }
    save_preds(f"{OUT}/preds_{name}.csv", nctids, labels, probs, RUN_ID)
    print(name, json.dumps(results[name], indent=2), flush=True)

# provenance check vs authors' shipped predictions
ship = {}
rows = list(csv.reader(open("results/phase_II_test.csv", newline="")))[1:]
for r in rows: ship[r[0]] = float(r[3])
nctids, labels, probs = predict(model, test_loader)
deltas, pairs = [], []
for n, p in zip(nctids, probs):
    if n in ship:
        deltas.append(abs(p - ship[n])); pairs.append((p, ship[n]))
results["provenance_vs_shipped"] = {
    "n_matched": len(deltas),
    "mean_abs_prob_diff": float(np.mean(deltas)),
    "max_abs_prob_diff": float(np.max(deltas)),
    "pearson_r": float(np.corrcoef([a for a,_ in pairs],[b for _,b in pairs])[0,1]),
    "note": "our checkpoint-eval probs vs authors' shipped results/phase_II_test.csv predictions",
}
results["elapsed_seconds"] = round(time.time() - t_start, 1)
json.dump(results, open(f"{OUT}/metrics.json", "w"), indent=2)
print("PROVENANCE:", json.dumps(results["provenance_vs_shipped"], indent=2))
print("saved", f"{OUT}/metrics.json")
